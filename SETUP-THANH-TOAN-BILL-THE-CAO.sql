-- BDShopVN: lưu thông tin thanh toán và bill để Admin kiểm tra.
-- Chạy trong Supabase Dashboard > SQL Editor bằng tài khoản chủ dự án.
create table if not exists public.payment_submissions (
  id bigint generated by default as identity primary key,
  order_code text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  method text not null check (method in ('bank','card')),
  status text not null default 'Chờ kiểm tra' check (status in ('Chờ kiểm tra','Đã xác nhận','Từ chối')),
  bill_path text,
  card_provider text,
  card_denomination integer,
  card_code text,
  card_serial text,
  card_fee_percent integer,
  notes text,
  admin_note text,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);
create index if not exists payment_submissions_order_code_idx on public.payment_submissions(order_code);
alter table public.payment_submissions enable row level security;
drop policy if exists "payment submission user insert own" on public.payment_submissions;
create policy "payment submission user insert own" on public.payment_submissions for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "payment submission user read own" on public.payment_submissions;
create policy "payment submission user read own" on public.payment_submissions for select to authenticated using (auth.uid() = user_id);
drop policy if exists "payment submission admin read" on public.payment_submissions;
create policy "payment submission admin read" on public.payment_submissions for select to authenticated using (public.is_bloxshop_admin());
drop policy if exists "payment submission admin update" on public.payment_submissions;
create policy "payment submission admin update" on public.payment_submissions for update to authenticated using (public.is_bloxshop_admin()) with check (public.is_bloxshop_admin());

insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('payment-bills','payment-bills',false,5242880,array['image/jpeg','image/png','image/webp','image/gif','application/pdf'])
on conflict (id) do update set public=false,file_size_limit=5242880,allowed_mime_types=array['image/jpeg','image/png','image/webp','image/gif','application/pdf'];

drop policy if exists "payment bill user upload own folder" on storage.objects;
create policy "payment bill user upload own folder" on storage.objects for insert to authenticated
with check (bucket_id='payment-bills' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "payment bill user read own folder" on storage.objects;
create policy "payment bill user read own folder" on storage.objects for select to authenticated
using (bucket_id='payment-bills' and ((storage.foldername(name))[1] = auth.uid()::text or public.is_bloxshop_admin()));
drop policy if exists "payment bill admin delete" on storage.objects;
create policy "payment bill admin delete" on storage.objects for delete to authenticated
using (bucket_id='payment-bills' and public.is_bloxshop_admin());
